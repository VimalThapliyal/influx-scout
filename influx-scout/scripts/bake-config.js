/**
 * Bakes owner Supabase credentials into engine/owner-config.js
 * so distributed builds never ask teammates for DB keys.
 *
 * Reads from influencer-platform/.env.local (or env vars).
 * Run automatically before start / dist.
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const platformEnv = path.join(root, "..", ".env.local");
const outFile = path.join(root, "engine", "owner-config.js");

function loadEnvFile(filePath) {
  const out = {};
  if (!fs.existsSync(filePath)) return out;
  const text = fs.readFileSync(filePath, "utf8");
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i < 0) continue;
    const k = t.slice(0, i).trim();
    let v = t.slice(i + 1).trim();
    if (
      (v.startsWith('"') && v.endsWith('"')) ||
      (v.startsWith("'") && v.endsWith("'"))
    ) {
      v = v.slice(1, -1);
    }
    out[k] = v;
  }
  return out;
}

const fileEnv = loadEnvFile(platformEnv);
const url = (
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  fileEnv.NEXT_PUBLIC_SUPABASE_URL ||
  ""
).replace(/\/$/, "");
const key =
  process.env.SUPABASE_SERVICE_ROLE_KEY ||
  fileEnv.SUPABASE_SERVICE_ROLE_KEY ||
  "";

if (!url || !key) {
  console.error(
    "bake-config: Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY.\n" +
      "Add them to influencer-platform/.env.local then re-run."
  );
  process.exit(1);
}

const body = `/**
 * AUTO-GENERATED — do not commit.
 * Owner Supabase project. Teammates only supply a YouTube API key.
 * Generated by scripts/bake-config.js
 */
module.exports = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseKey: ${JSON.stringify(key)},
};
`;

fs.writeFileSync(outFile, body, "utf8");
console.log("bake-config: wrote engine/owner-config.js");
